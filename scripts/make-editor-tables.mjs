/*
 * Writes the two tables the editing panel is built from, so that nothing the format defines is typed by hand:
 *
 *   src/core/linter-tables.ts   the linter's own tables (lint-booklet.py): the format version, each kind and the settings it takes,
 *                               the kinds that take no id, the question kinds, the query views, the icon names, and the source of the
 *                               line patterns it reads with. They are read by running the linter's module (importlib), the way the
 *                               kit's make-cheatsheet.py does, so a table is the linter's object and not a copy of its text.
 *   src/core/pieces-table.ts    every file in pieces/ (the text of each piece the panel places), as written.
 *
 *     node scripts/make-editor-tables.mjs            write both
 *     node scripts/make-editor-tables.mjs --check    write nothing; exit 1 and name the file if one is stale
 *
 *   --booklet DIR   the booklet repository that holds lint-booklet.py (default $BOOKLET_REPO, else /workspace/booklet)
 *   --python PATH   the Python that reads the linter (default python3)
 *
 * test/editor-tables.test.mjs runs the same read again, separately, and fails when src/core/linter-tables.ts differs from the
 * linter or a kind has no piece. The generated files are committed: a build does not need Python or the booklet repository.
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..");

function arg(name, dflt) {
	const i = process.argv.indexOf(name);
	return i >= 0 && process.argv[i + 1] ? process.argv[i + 1] : dflt;
}
const CHECK = process.argv.includes("--check");
const BOOKLET = resolve(arg("--booklet", process.env["BOOKLET_REPO"] || "/workspace/booklet"));
const PYTHON = arg("--python", "python3");

function fail(msg) {
	process.stderr.write(`make-editor-tables: ${msg}\n`);
	process.exit(2);
}

/** The Python that prints the linter's tables as JSON. -I and no bytecode: nothing of the user's Python leaks in, nothing is written beside the linter. */
export const PY_TABLES = String.raw`
import importlib.util, json, re, sys
sys.dont_write_bytecode = True
spec = importlib.util.spec_from_file_location("lint_booklet_for_plugin", sys.argv[1])
m = importlib.util.module_from_spec(spec)
spec.loader.exec_module(m)
def pat(r):
    extra = r.flags & ~(re.UNICODE | re.IGNORECASE)
    if extra:
        raise SystemExit("pattern %r has flags the plugin does not carry: %d" % (r.pattern, extra))
    return {"source": r.pattern, "flags": "i" if r.flags & re.IGNORECASE else ""}
names = ["CALLOUT_LINE", "CALLOUT_ANY", "ID_PATTERN", "FENCE_LINE", "THEMATIC_BREAK", "BULLET", "TASK", "NUMBERED", "NESTED_BULLET"]
print(json.dumps({
    "FORMAT_VERSION": m.FORMAT_VERSION,
    "KIND_SETTINGS": [[k, list(v)] for k, v in m.KIND_SETTINGS.items()],
    "NO_ID_KINDS": list(m.NO_ID_KINDS),
    "QUESTION_KINDS": sorted(m.QUESTION_KINDS),
    "NUMBER_SETTINGS": list(m.NUMBER_SETTINGS),
    "QUERY_VIEWS": list(m.QUERY_VIEWS),
    "ICON_NAMES": sorted(m.ICON_NAMES),
    "patterns": {n: pat(getattr(m, n)) for n in names},
}))
`;

/** The linter's tables as the Python above prints them. */
export function readLinterTables(linter, python = PYTHON) {
	const r = spawnSync(python, ["-I", "-B", "-c", PY_TABLES, linter], { encoding: "utf8" });
	if (r.error) fail(`could not run ${python}: ${r.error.message}`);
	if (r.status !== 0) fail(`reading the linter's tables failed:\n${r.stderr}`);
	return JSON.parse(r.stdout);
}

/** A piece's file is "<group> - <label>.md"; the group word says where the panel lists it. */
export const GROUPS = { Structure: "structure", Q: "questions", Reading: "reading", Data: "data", View: "views" };

export function readPieces(dir) {
	const files = readdirSync(dir).filter((f) => f.endsWith(".md")).sort();
	if (!files.length) fail(`no pieces in ${dir}`);
	return files.map((file) => {
		const m = /^([^-]+?) - (.+)\.md$/.exec(file);
		if (!m || !GROUPS[m[1]]) fail(`${file}: a piece's file is "<${Object.keys(GROUPS).join(" | ")}> - <label>.md"`);
		return { file, group: GROUPS[m[1]], label: m[2], text: readFileSync(join(dir, file), "utf8") };
	});
}

const TABLES_HEAD = (linter, version) =>
	`/*\n * GENERATED by scripts/make-editor-tables.mjs from ${linter} (format ${version}). Do not edit by hand: run\n` +
	` * \`node scripts/make-editor-tables.mjs\`. test/editor-tables.test.mjs fails when this differs from the linter.\n` +
	` * KIND_SETTINGS keeps the linter's order; a flag is a bare word and \`key:\` a setting written key:value. Each pattern is the\n` +
	` * linter's own regular expression source, compiled by editor-patterns.ts.\n */\n`;

export function tablesModule(t, linter) {
	return (
		TABLES_HEAD(linter, t.FORMAT_VERSION) +
		`export interface LinterTables {\n\tFORMAT_VERSION: string;\n\tKIND_SETTINGS: [string, string[]][];\n\tNO_ID_KINDS: string[];\n\tQUESTION_KINDS: string[];\n` +
		`\tNUMBER_SETTINGS: string[];\n\tQUERY_VIEWS: string[];\n\tICON_NAMES: string[];\n\tpatterns: Record<string, { source: string; flags: string }>;\n}\n\n` +
		`export const LINTER_TABLES: LinterTables = ${JSON.stringify(t, null, "\t")};\n`
	);
}

export function piecesModule(list) {
	return (
		`/*\n * GENERATED by scripts/make-editor-tables.mjs from pieces/: each file as written. Do not edit by hand: run\n` +
		` * \`node scripts/make-editor-tables.mjs\`. test/editor-tables.test.mjs fails when this differs from pieces/.\n */\n` +
		`export interface PieceSource {\n\t/** The file in pieces/. */\n\tfile: string;\n\tgroup: "structure" | "questions" | "reading" | "data" | "views";\n\tlabel: string;\n\t/** The text the panel places, with \`new-\` words for the ids it makes. */\n\ttext: string;\n}\n\n` +
		`export const PIECE_SOURCES: readonly PieceSource[] = ${JSON.stringify(list, null, "\t")};\n`
	);
}

function main() {
	const linter = join(BOOKLET, "lint-booklet.py");
	if (!existsSync(linter)) fail(`missing ${linter} (see --booklet)`);
	const outputs = {
		"src/core/linter-tables.ts": tablesModule(readLinterTables(linter), "lint-booklet.py"),
		"src/core/pieces-table.ts": piecesModule(readPieces(join(ROOT, "pieces"))),
	};
	const stale = [];
	for (const [rel, want] of Object.entries(outputs)) {
		const p = join(ROOT, rel);
		const have = existsSync(p) ? readFileSync(p, "utf8") : null;
		if (have === want) continue;
		if (CHECK) stale.push(rel);
		else {
			mkdirSync(dirname(p), { recursive: true });
			writeFileSync(p, want);
			process.stdout.write(`wrote ${rel}\n`);
		}
	}
	if (CHECK) {
		if (stale.length) {
			process.stdout.write(`stale: ${stale.join(", ")}\n(run node scripts/make-editor-tables.mjs)\n`);
			process.exit(1);
		}
		process.stdout.write("src/core/linter-tables.ts and src/core/pieces-table.ts are up to date\n");
	}
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
