/* Writes themes/fonts.css: the two fonts the paper looks use, as @font-face rules whose src is a base64 data: URI, because
   Obsidian loads only styles.css and a plugin cannot rely on any other file or on the network at run time.
   Reads the woff2 files committed in themes/font-files/ (latin subset only: Spanish, French and English are covered;
   latin-ext, Vietnamese and the rest fall back to the system font). Run: node scripts/make-fonts-css.mjs
   then: node scripts/build-styles.mjs
   Fonts: Lexend (variable, wght 100 to 900), Copyright 2019 The Lexend Project Authors, and Atkinson Hyperlegible,
   Copyright 2020 Braille Institute of America, Inc.; both SIL Open Font License 1.1 (docs/third-party/). Files from
   @fontsource-variable/lexend 5.3.0 and @fontsource/atkinson-hyperlegible 5.3.0. */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const LATIN = "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,U+0308,U+0329,U+2000-206F,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD";

const FACES = [
	{ family: "Lexend", file: "lexend-latin-wght-normal.woff2", style: "normal", weight: "100 900", format: "woff2" },
	{ family: "Atkinson Hyperlegible", file: "atkinson-hyperlegible-latin-400-normal.woff2", style: "normal", weight: "400", format: "woff2" },
	{ family: "Atkinson Hyperlegible", file: "atkinson-hyperlegible-latin-400-italic.woff2", style: "italic", weight: "400", format: "woff2" },
	{ family: "Atkinson Hyperlegible", file: "atkinson-hyperlegible-latin-700-normal.woff2", style: "normal", weight: "700", format: "woff2" },
];

let css = `/* Generated by scripts/make-fonts-css.mjs from themes/font-files/*.woff2. Do not edit.
   Lexend: Copyright 2019 The Lexend Project Authors. Atkinson Hyperlegible: Copyright 2020 Braille Institute of America, Inc.
   Both under the SIL Open Font License 1.1 (docs/third-party/). The fonts are inside this file: nothing is fetched. */
`;
const sizes = [];
for (const f of FACES) {
	const b64 = readFileSync(join(root, "themes/font-files", f.file)).toString("base64");
	const rule = `@font-face {
	font-family: "${f.family}";
	font-style: ${f.style};
	font-weight: ${f.weight};
	font-display: swap;
	src: url("data:font/woff2;base64,${b64}") format("${f.format}");
	unicode-range: ${LATIN};
}
`;
	sizes.push(`${f.family} ${f.style} ${f.weight}: ${rule.length} bytes`);
	css += rule;
}
writeFileSync(join(root, "themes/fonts.css"), css);
console.log(sizes.join("\n") + `\nthemes/fonts.css: ${Buffer.byteLength(css)} bytes`);
